#!/usr/bin/env python3
"""Writes cmake/Sources.cmake: the game source files by original module, each with the compiler options it was
originally built with, from Iblis Codex's build/units.json and build/config.json. Run after a sync that adds,
removes or moves files:

    python tools/cmake_sources.py CODEX_DIR

Options every file gets from CMakeLists.txt (/c, /nologo, /Z7, /MT, /Zl) are left out.
"""
import sys, os, json, collections

ENGINE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DROP = {"/c", "/nologo", "/Z7", "/Zl", "/MT"}


def main():
    codex = sys.argv[1]
    units = json.load(open(os.path.join(codex, "build", "units.json")))["units"]
    cfg = json.load(open(os.path.join(codex, "build", "config.json")))
    by_module = collections.defaultdict(list)
    by_flags = collections.defaultdict(list)
    for u in sorted(units, key=lambda u: u["file"].lower()):
        mod = u["file"].split("/")[1]
        f = u.get("flags") or cfg.get("module_flags", {}).get(mod) or cfg["flags"]
        by_module[mod].append(u["file"])
        by_flags[tuple(x for x in f if x not in DROP)].append(u["file"])
    out = ["# Generated by tools/cmake_sources.py from Iblis Codex's build/units.json: the game source files by original",
           "# module, and the compiler options each was originally built with (Diablo II 1.14d, Visual C++ 2005 SP1).", "",
           "set(IBLIS_MODULES %s)" % " ".join(sorted(by_module)), ""]
    for mod in sorted(by_module):
        out.append("set(IBLIS_%s_SOURCES" % mod)
        out += ["    %s" % f for f in by_module[mod]]
        out += [")", ""]
    for i, (fl, files) in enumerate(sorted(by_flags.items(), key=lambda kv: -len(kv[1]))):
        out.append("# %s" % " ".join(fl))
        out.append("set_source_files_properties(")
        out += ["    %s" % f for f in files]
        out.append('    PROPERTIES COMPILE_OPTIONS "%s")' % ";".join(fl))
        out.append("")
    open(os.path.join(ENGINE, "cmake", "Sources.cmake"), "w", newline="\n").write("\n".join(out))
    print("%d files, %d modules, %d option sets" % (len(units), len(by_module), len(by_flags)))


if __name__ == "__main__":
    main()
